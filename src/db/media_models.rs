//! Types of time-based documents (audio, video; schema_v85, CRUD in `media.rs`): the per-document row
//! with its JSON columns typed (`engines`, `speakers`, `phases`), the segments (speech with timed words,
//! subtitles, slides, scenes, sounds) and the time range of a video still. Re-exported by `models.rs`.
//! Times are milliseconds from the start of the file.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

/// Audio or video (`media_documents.kind`).
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum MediaKind {
    #[default]
    Audio,
    Video,
}

/// What a segment holds (`media_segments.kind`). Speech and slides are source text (`asr`/`ocr`), scenes
/// and sounds are generated by a model.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Hash, PartialOrd, Ord, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum SegmentKind {
    #[default]
    Speech,
    Subtitle,
    Slide,
    Scene,
    Sound,
}

macro_rules! text_enum {
    ($t:ty { $($v:ident = $s:literal),* }) => {
        impl $t {
            /// The value stored in the database.
            pub fn as_str(self) -> &'static str {
                match self { $(Self::$v => $s),* }
            }
            /// Parses a stored value; `None` for an unknown one.
            pub fn parse(s: &str) -> Option<Self> {
                match s { $($s => Some(Self::$v),)* _ => None }
            }
        }
    };
}
text_enum!(MediaKind { Audio = "audio", Video = "video" });
text_enum!(SegmentKind { Speech = "speech", Subtitle = "subtitle", Slide = "slide", Scene = "scene", Sound = "sound" });

/// A speaker found in the file: `id` as in `MediaSegment::speaker`, the automatic `label`
/// ("Speaker 2") and the name the user gave, if any.
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct MediaSpeaker {
    pub id: i64,
    pub label: String,
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
}

impl MediaSpeaker {
    /// What passages and headings call the speaker: the given name, else the label.
    pub fn display(&self) -> &str {
        self.name.as_deref().filter(|n| !n.trim().is_empty()).unwrap_or(&self.label)
    }
}

/// How far a processing phase came (`media_documents.phases`, keyed by phase name such as
/// `transcribing`): everything up to `done_ms` is final, so resuming starts there.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct MediaPhase {
    pub state: PhaseState,
    pub done_ms: i64,
}

#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum PhaseState {
    #[default]
    InProgress,
    Done,
    /// Not run on purpose (no model, no picture decoder on this device); the reason is shown elsewhere.
    Skipped,
}

/// Which engine wrote which stretch in a phase (`media_documents.engines`), e.g. phase `transcribing`,
/// engine `whisper:large-v3-turbo-q5_0`, 0–3 600 000 ms. A fallback that took over part of the file
/// shows as a second span; generated passages name their engine from here (`generator`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct EngineSpan {
    pub phase: String,
    pub engine: String,
    pub t0_ms: i64,
    pub t1_ms: i64,
}

/// One audio or video document (`media_documents`).
#[derive(Debug, Clone, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct MediaDocument {
    pub document_id: i64,
    pub kind: MediaKind,
    pub duration_ms: i64,
    pub width: Option<i64>,
    pub height: Option<i64>,
    /// Main language of the speech (BCP-47).
    pub language: Option<String>,
    pub engines: Vec<EngineSpan>,
    pub speakers: Vec<MediaSpeaker>,
    pub phases: BTreeMap<String, MediaPhase>,
    /// The whole file went through every phase.
    pub complete: bool,
}

impl MediaDocument {
    /// Display name of speaker `id`: from `speakers`, else "Speaker {id + 1}".
    pub fn speaker_name(&self, id: i64) -> String {
        self.speakers.iter().find(|s| s.id == id).map(|s| s.display().to_string()).unwrap_or_else(|| format!("Speaker {}", id + 1))
    }

    /// The engine that wrote phase `phase` at time `t_ms` (the last matching span wins).
    pub fn engine_at(&self, phase: &str, t_ms: i64) -> Option<&str> {
        self.engines.iter().rev().find(|e| e.phase == phase && e.t0_ms <= t_ms && t_ms <= e.t1_ms).map(|e| e.engine.as_str())
    }
}

/// One timed word of a speech segment (`media_segments.words`, JSON with short keys because a long
/// file has hundreds of thousands): its text as it appears in the segment text, its time and — where
/// the speakers were found inside a recognition window — its speaker.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct MediaWord {
    #[serde(rename = "w")]
    pub text: String,
    #[serde(rename = "s")]
    pub t0_ms: i64,
    #[serde(rename = "e")]
    pub t1_ms: i64,
    #[serde(rename = "sp", default, skip_serializing_if = "Option::is_none")]
    pub speaker: Option<i64>,
}

/// One stored result of the expensive steps (`media_segments`). `id` is 0 until stored. `text` is
/// authoritative; `words` (speech only, may be empty) give times and speakers of its words in order.
/// `speaker` is the segment's speaker where its words name none.
#[derive(Debug, Clone, Default, PartialEq, Serialize, Deserialize)]
pub struct MediaSegment {
    pub id: i64,
    pub document_id: i64,
    pub t_start_ms: i64,
    pub t_end_ms: i64,
    pub kind: SegmentKind,
    pub speaker: Option<i64>,
    pub text: String,
    pub words: Vec<MediaWord>,
    pub language: Option<String>,
    pub confidence: Option<f64>,
    /// The still a slide or scene was read from.
    pub page_image_id: Option<i64>,
    pub generated: bool,
}

/// A video still (`page_images` with a time range), its position in the document text included.
#[derive(Debug, Clone, Copy, Default, PartialEq, Eq, Serialize, Deserialize)]
pub struct FrameTime {
    pub page_image_id: i64,
    pub page: i64,
    pub t_start_ms: i64,
    pub t_end_ms: i64,
    pub char_start: Option<i64>,
    pub char_end: Option<i64>,
}
